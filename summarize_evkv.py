"""Turn paired_eval_kv.py CSVs into the report's K/V table (LaTeX on stdout).

  python summarize_evkv.py <dir with metrics_*.csv> > report/tables/kv_eval.tex

Rows are arms, averaged over every pair that has all arms logged; also counts
the pairs on which the arm lands closer to the real weather render than the
un-injected regeneration (err < 1).
"""
import csv
import glob
import os
import sys
from collections import defaultdict

FIELDS = ['shard', 'variant', 'params', 'ref', 'ref_params', 'arm', 'lam', 'window',
          'n_inj', 'frac', 'cos', 'err', 'psnr_weather', 'psnr_clear']


def label(arm):
    if arm == 'base':
        return 'no injection'
    lam, win = arm.split('=')[1].split('|')
    lo, hi = (float(v) for v in win.split('-'))
    if lo == 0 and hi == 1:
        w = 'all steps'
    elif hi == 1:
        w = f'$\\sigma\\ge{lo:g}$'
    elif lo == 0:
        w = f'$\\sigma<{hi:g}$'
    else:
        w = f'$\\sigma\\in[{lo:g},{hi:g}]$'
    return f'$\\lambda{{=}}{float(lam):g}$, {w}'


def main(d):
    rows = []
    for f in sorted(glob.glob(os.path.join(d, 'metrics*.csv'))):
        for r in csv.reader(open(f)):
            if len(r) == len(FIELDS) and r[0] != 'shard':
                rows.append(dict(zip(FIELDS, r)))
    by_pair = defaultdict(dict)
    for r in rows:
        by_pair[(r['shard'], r['variant'])][r['arm']] = r
    n_arms = max(len(v) for v in by_pair.values())
    pairs = {k: v for k, v in by_pair.items() if len(v) == n_arms}
    arms = sorted({a for v in pairs.values() for a in v},
                  key=lambda a: (a != 'base', a))

    def mean(a, k):
        vals = [float(p[a][k]) for p in pairs.values() if p[a].get(k)]
        return sum(vals) / len(vals) if vals else float('nan')

    n = len(pairs)
    print(f'% {n} pairs from {sorted({s for s, _ in pairs})}; generated by summarize_evkv.py')
    print('\\begin{table}[!htb]\n\\centering\\small')
    print('\\begin{tabular}{lccccccc}\n\\toprule')
    print('arm & frac & cos & err$\\downarrow$ & W$\\uparrow$ & C$\\uparrow$ & err$<1$ & W$>$base \\\\\n\\midrule')
    for a in arms:
        closer = sum(float(p[a]['err']) < 1.0 for p in pairs.values())
        wins = sum(float(p[a]['psnr_weather']) > float(p['base']['psnr_weather'])
                   for p in pairs.values())
        print(f"{label(a)} & {mean(a, 'frac'):.2f} & {mean(a, 'cos'):.2f} & "
              f"{mean(a, 'err'):.2f} & {mean(a, 'psnr_weather'):.1f} & "
              f"{mean(a, 'psnr_clear'):.1f} & {closer if a != 'base' else '--'}/{n} & "
              f"{wins if a != 'base' else '--'}/{n} \\\\")
    print('\\bottomrule\n\\end{tabular}')
    print(f'\\caption{{\\textbf{{Paired ground-truth evaluation of reference injection}} '
          f'({n} held-out scene-0 pairs, means). frac: fraction of the true weather difference '
          f'realised along its direction; cos: cosine of the change with the true difference; '
          f'err: distance to the real weather render relative to the un-injected regeneration '
          f'(${{<}}1$ = closer); W$>$base: pairs where pixel PSNR to the weather render beats no injection; W / C: PSNR (dB) to the real weather render / to the clear video. '
          f'References are weather renders of a \\emph{{different}} camera path with the nearest '
          f'weather vector.}}')
    print('\\label{tab:kv}\n\\end{table}')


if __name__ == '__main__':
    main(sys.argv[1])
